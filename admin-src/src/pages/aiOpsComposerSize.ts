// Older iOS WebViews do not support field-sizing: content. Keep their input
// autosizing off the synchronous keystroke path and outside the chat layout.
const sizingProperties = ['box-sizing', 'width', 'font-family', 'font-size', 'font-weight', 'font-style', 'font-variant', 'line-height', 'letter-spacing', 'text-indent', 'text-transform', 'padding-top', 'padding-bottom', 'padding-left', 'padding-right', 'border-top-width', 'border-bottom-width', 'border-left-width', 'border-right-width', 'word-break', 'overflow-wrap', 'white-space', 'tab-size'] as const;
const shadowStyle = 'position:fixed;left:-10000px;top:0;height:0;min-height:0;max-height:none;visibility:hidden;overflow:hidden;pointer-events:none;z-index:-1000;resize:none;';

export function watchMiniComposerSize(input: HTMLTextAreaElement) {
  let disposed = false, recalibrate = true;
  let frame: number | null = null;
  let width = -1, lastHeight = '';
  let boxSizing = '', padding = 0, border = 0, minHeight = 46, maxHeight = 112;
  const originalHeight = input.style.height;
  const shadow = document.createElement('textarea');
  shadow.tabIndex = -1;
  shadow.setAttribute('aria-hidden', 'true');
  shadow.setAttribute('data-mini-composer-measure', '');
  shadow.readOnly = true;
  shadow.style.cssText = shadowStyle;
  document.body.appendChild(shadow);

  const measure = () => {
    frame = null;
    if (disposed || !input.isConnected || document.visibilityState === 'hidden') return;
    if (recalibrate) {
      const measuredWidth = input.getBoundingClientRect().width;
      // Hidden tab panes must not cache a zero-width measurement.
      if (measuredWidth <= 0) return;
      const style = window.getComputedStyle(input);
      const number = (property: string) => parseFloat(style.getPropertyValue(property)) || 0;
      shadow.style.cssText = shadowStyle;
      for (const property of sizingProperties) shadow.style.setProperty(property, style.getPropertyValue(property));
      // Border-box width follows the real flex item rather than its CSS width:0.
      boxSizing = style.getPropertyValue('box-sizing');
      padding = number('padding-top') + number('padding-bottom');
      border = number('border-top-width') + number('border-bottom-width');
      const horizontal = number('padding-left') + number('padding-right') + number('border-left-width') + number('border-right-width');
      shadow.style.width = `${boxSizing === 'border-box' ? measuredWidth : Math.max(0, measuredWidth - horizontal)}px`;
      let line = number('line-height');
      if (!line) {
        shadow.value = ' ';
        line = Math.max(1, shadow.scrollHeight - padding);
      }
      const extra = boxSizing === 'border-box' ? padding + border : 0;
      minHeight = line + extra;
      maxHeight = line * 4 + extra;
      width = measuredWidth;
      recalibrate = false;
    }
    shadow.value = input.value || ' ';
    const height = shadow.scrollHeight + (boxSizing === 'border-box' ? border : -padding);
    const next = `${Math.ceil(Math.max(minHeight, Math.min(maxHeight, height)))}px`;
    // Browser paints the input's updated value even if its line count is stable.
    // Do not reset height to 0/auto or selection/scroll on each keystroke.
    if (next !== lastHeight || input.style.height !== next) {
      input.style.height = next;
      lastHeight = next;
    }
  };
  const refresh = (stylesChanged = false) => {
    if (disposed) return;
    recalibrate = recalibrate || stylesChanged;
    if (frame === null) frame = window.requestAnimationFrame(measure);
  };
  const observer = typeof ResizeObserver === 'undefined' ? null : new ResizeObserver((entries) => {
    const entry = entries.find((item) => item.target === input);
    if (!entry) return;
    // Ignore height-only notifications generated by our own measured height.
    const nextWidth = entry.borderBoxSize?.[0]?.inlineSize;
    const measuredWidth = Number.isFinite(nextWidth) ? nextWidth! : input.getBoundingClientRect().width;
    if (Math.abs(measuredWidth - width) > 0.5) refresh(true);
  });
  observer?.observe(input);
  const resize = () => refresh(true);
  const visibility = () => { if (document.visibilityState !== 'hidden') refresh(true); };
  const fonts = document.fonts;
  window.addEventListener('resize', resize);
  window.addEventListener('orientationchange', resize);
  document.addEventListener('visibilitychange', visibility);
  fonts?.addEventListener?.('loadingdone', resize);
  refresh();
  return {
    refresh,
    dispose() {
      if (disposed) return;
      disposed = true;
      if (frame !== null) window.cancelAnimationFrame(frame);
      observer?.disconnect();
      window.removeEventListener('resize', resize);
      window.removeEventListener('orientationchange', resize);
      document.removeEventListener('visibilitychange', visibility);
      fonts?.removeEventListener?.('loadingdone', resize);
      shadow.value = '';
      shadow.remove();
      if (input.style.height === lastHeight) input.style.height = originalHeight;
    },
  };
}
