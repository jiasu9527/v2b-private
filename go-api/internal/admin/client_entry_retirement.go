// The snapshot holds complete configuration rows in the database, never in a
// tool response. Live probe samples are omitted from the CAS so a heartbeat
// cannot invalidate an otherwise unchanged plan.
func loadRetirementSnapshot(ctx context.Context, tx *sql.Tx, req ClientEntryRetirementPreviewRequest, lockUsers bool) (retirementSnapshot, error) {
	var s retirementSnapshot
	policies, err := readClientEntryUserPolicies(ctx, tx)
	if err != nil {
		return s, err
	}
	s.Policies = policies
	err = tx.QueryRowContext(ctx, `SELECT jsonb_build_object(
 'policies',COALESCE((SELECT jsonb_agg(p ORDER BY id) FROM v2_client_entry_user_policy p),'[]'::jsonb),
 'groups',COALESCE((SELECT jsonb_agg(g ORDER BY id) FROM v2_client_entry_user_policy_split_group g),'[]'::jsonb),
 'members',COALESCE((SELECT jsonb_agg(m ORDER BY id) FROM v2_client_entry_user_policy_member m),'[]'::jsonb),
 'assignments',COALESCE((SELECT jsonb_agg(a ORDER BY id) FROM v2_client_entry_user_policy_split_assignment a),'[]'::jsonb),
 'collections',COALESCE((SELECT jsonb_agg(c ORDER BY id) FROM v2_client_entry_collection c),'[]'::jsonb),
 'collection_members',COALESCE((SELECT jsonb_agg(m ORDER BY collection_id,policy_id,split_group_id) FROM v2_client_entry_collection_member m),'[]'::jsonb),
 'group_ips',COALESCE((SELECT jsonb_agg(i ORDER BY id) FROM v2_client_entry_group_ip i),'[]'::jsonb),
 'monitors',COALESCE((SELECT jsonb_agg(m ORDER BY id) FROM v2_client_entry_monitor m),'[]'::jsonb),
 'targets',COALESCE((SELECT jsonb_agg(t ORDER BY id) FROM v2_client_entry_monitor_target t),'[]'::jsonb),
 'monitor_probes',COALESCE((SELECT jsonb_agg(p ORDER BY id) FROM v2_client_entry_monitor_probe p),'[]'::jsonb),
 'monitor_config',(SELECT to_jsonb(c) FROM v2_client_entry_monitor_config c WHERE id=1),
 'pool',COALESCE((SELECT jsonb_agg(p ORDER BY id) FROM v2_client_entry_backup_ip p),'[]'::jsonb)
)`).Scan(&s.Raw)
	if err != nil {
		return s, err
	}
	// Keep the typed policy loader above, whose SplitGroups include leaf state.
	var raw struct {
		Assignments       []retirementAssignment       `json:"assignments"`
		Collections       []retirementHost             `json:"collections"`
		CollectionMembers []retirementCollectionMember `json:"collection_members"`
		GroupIPs          []struct {
			IP string `json:"ip"`
		} `json:"group_ips"`
		Pool     []retirementPool    `json:"pool"`
		Targets  []retirementTarget  `json:"targets"`
		Monitors []retirementMonitor `json:"monitors"`
	}
	if err = json.Unmarshal(s.Raw, &raw); err != nil {
		return s, err
	}
	// Collections persist entry_host, whereas node records use host.
	var collections struct {
		Items []struct {
			ID   int64  `json:"id"`
			Host string `json:"entry_host"`
		} `json:"collections"`
	}
	if err = json.Unmarshal(s.Raw, &collections); err != nil {
		return s, err
	}
	s.Assignments = raw.Assignments
	s.CollectionMembers = raw.CollectionMembers
	s.GroupIPs = raw.GroupIPs
	s.Pool = raw.Pool
	s.Targets = raw.Targets
	s.Monitors = raw.Monitors
	for _, c := range collections.Items {
		s.Collections = append(s.Collections, retirementHost{c.ID, c.Host})
	}
	suffix := ""
	if lockUsers {
		suffix = " FOR SHARE OF u"
	}
	rows, err := tx.QueryContext(ctx, `SELECT u.id,u.email,COALESCE(u.plan_id,0),COALESCE(u.created_at,0) FROM v2_user u WHERE EXISTS(SELECT 1 FROM v2_client_entry_user_policy_split_assignment a WHERE a.user_id=u.id AND a.group_id=ANY($1::bigint[])) ORDER BY u.id`+suffix, req.GroupIDs)
	if err != nil {
		return s, err
	}
	for rows.Next() {
		var u retirementUser
		if err = rows.Scan(&u.ID, &u.Email, &u.PlanID, &u.CreatedAt); err != nil {
			rows.Close()
			return s, err
		}
		s.Users = append(s.Users, u)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return s, err
	}
	tables := []string{}
	for _, table := range managedServerTypeTable {
		tables = append(tables, table)
	}
	sort.Strings(tables)
	for _, table := range tables {
		var exists bool
		if err = tx.QueryRowContext(ctx, `SELECT to_regclass($1) IS NOT NULL`, table).Scan(&exists); err != nil {
			return s, err
		}
		if !exists {
			continue
		}
		rows, err = tx.QueryContext(ctx, `SELECT id,COALESCE(host,'') FROM `+quoteIdentifier(table)+` ORDER BY id`)
		if err != nil {
			return s, err
		}
		for rows.Next() {
			var n retirementHost
			if err = rows.Scan(&n.ID, &n.Host); err != nil {
				rows.Close()
				return s, err
			}
			s.Nodes = append(s.Nodes, n)
		}
		err = rows.Err()
		rows.Close()
		if err != nil {
			return s, err
		}
	}
	return s, nil
}

func retirementSameHost(a, b string) bool {
	ca, aok := canonicalClientEntryBackupIPHost(a)
	cb, bok := canonicalClientEntryBackupIPHost(b)
	if aok && bok {
		return ca == cb
	}
	return strings.EqualFold(strings.TrimSuffix(strings.TrimSpace(a), "."), strings.TrimSuffix(strings.TrimSpace(b), "."))
}
func retirementDigest(v any) string {
	raw, _ := json.Marshal(v)
	h := sha256.Sum256(raw)
	return hex.EncodeToString(h[:])
}
func retirementIDs(set map[int64]bool) []int64 {
	ids := make([]int64, 0, len(set))
	for id := range set {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	return ids
}
func retirementSet(ids []int64) map[int64]bool {
	m := map[int64]bool{}
	for _, id := range ids {
		m[id] = true
	}
	return m
}
func retirementMembersCover(dst, src []ClientEntryGroupMemberRecord) bool {
	members := map[string]bool{}
	for _, m := range dst {
		members[clientEntryMonitorNodeKey(m.ServerType, m.ServerID)] = true
	}
	for _, m := range src {
		if !members[clientEntryMonitorNodeKey(m.ServerType, m.ServerID)] {
			return false
		}
	}
	return len(src) > 0
}
func retirementUAConditionsCover(dst, src []cliententry.Condition) bool {
	dst = cliententry.RuntimeConditions("split", dst)
	src = cliententry.RuntimeConditions("split", src)
	return len(dst) == 0 || retirementDigest(dst) == retirementDigest(src)
}
func retirementGroupSort(g ClientEntryUserPolicySplitGroupRecord, p ClientEntryUserPolicyRecord) int64 {
	if g.GlobalSort != nil {
		return *g.GlobalSort
	}
	return p.Sort
}
func retirementPrecedes(a ClientEntryUserPolicySplitGroupRecord, ap ClientEntryUserPolicyRecord, b ClientEntryUserPolicySplitGroupRecord, bp ClientEntryUserPolicyRecord) bool {
	as, bs := retirementGroupSort(a, ap), retirementGroupSort(b, bp)
	if as != bs {
		return as < bs
	}
	if ap.ID != bp.ID {
		return ap.ID < bp.ID
	}
	return a.ID < b.ID
}

func buildRetirementPlan(req ClientEntryRetirementPreviewRequest, s retirementSnapshot, now int64) (retirementPlan, error) {
	p := retirementPlan{Preview: ClientEntryRetirementPreview{SelectedGroups: []ClientEntryRetirementGroup{}, RemovedAncestorIDs: []int64{}, RemovedPolicyIDs: []int64{}, IPs: []ClientEntryRetirementIP{}, Blockers: []string{}, Warnings: []string{"分配人数不是实际拉取人数；本操作不删除历史下发日志。", "用户需更新订阅才能获得回落入口；既有专线和特殊规则仍按原优先级命中。", "释放的是配置占用，不修改服务器网卡，也不把故障 IP 改成健康。回落人数仅证明规则条件覆盖，不能证明客户端已更新或连接成功。"}}}
	policies := map[int64]ClientEntryUserPolicyRecord{}
	groups := map[int64]ClientEntryUserPolicySplitGroupRecord{}
	children := map[int64][]int64{}
	for _, v := range s.Policies {
		policies[v.ID] = v
		for _, g := range v.SplitGroups {
			groups[g.ID] = g
			if g.ParentID != nil {
				children[*g.ParentID] = append(children[*g.ParentID], g.ID)
			}
		}
	}
	// Corrupt cross-policy parent links would make ON DELETE CASCADE extend
	// beyond the selected policy. Refuse the tree instead of guessing scope.
	for _, g := range groups {
		if g.ParentID != nil {
			parent, ok := groups[*g.ParentID]
			if !ok || parent.PolicyID != g.PolicyID {
				return p, fmt.Errorf("%w：入口组父子关系不完整", ErrClientEntryRetirementBlocked)
			}
		}
	}
	selected, replacements := retirementSet(req.GroupIDs), retirementSet(req.ReplacementGroupIDs)
	assignedGroup := map[int64]bool{}
	assignedCounts := map[int64]int64{}
	for _, a := range s.Assignments {
		assignedGroup[a.GroupID] = true
		assignedCounts[a.GroupID]++
		if selected[a.GroupID] || replacements[a.GroupID] {
			if g, ok := groups[a.GroupID]; !ok || a.PolicyID != g.PolicyID {
				return p, fmt.Errorf("%w：固定名单与所属规则不一致", ErrClientEntryRetirementBlocked)
			}
		}
	}
	relevantPolicies := map[int64]bool{req.FallbackPolicyID: true}
	for id := range selected {
		if g, ok := groups[id]; ok {
			relevantPolicies[g.PolicyID] = true
			if len(policies[g.PolicyID].ExtraNodes) > 0 {
				p.Preview.Blockers = append(p.Preview.Blockers, fmt.Sprintf("规则 %d 包含附加节点，需先核对附加节点的保留方案", g.PolicyID))
			}
		}
	}
	for id := range replacements {
		if g, ok := groups[id]; ok {
			relevantPolicies[g.PolicyID] = true
		}
	}
	for _, ids := range [][]int64{req.GroupIDs, req.ReplacementGroupIDs} {
		for _, id := range ids {
			g, ok := groups[id]
			if !ok || !g.IsLeaf || len(children[id]) > 0 {
				return p, fmt.Errorf("%w：%d 不是当前固定叶子组", ErrClientEntryRetirementInvalid, id)
			}
			policy := policies[g.PolicyID]
			if policy.Mode != "split" || policy.Action != cliententry.ActionOverride {
				return p, fmt.Errorf("%w：%d 不是独立入口固定组", ErrClientEntryRetirementInvalid, id)
			}
		}
	}
	doomed := retirementSet(req.GroupIDs)
	for changed := true; changed; {
		changed = false
		for id, g := range groups {
			if doomed[id] || len(children[id]) == 0 {
				continue
			}
			all := true
			for _, child := range children[id] {
				all = all && doomed[child]
			}
			if all {
				if g.EntryHost != "" || g.GlobalSort != nil || assignedGroup[id] {
					return p, fmt.Errorf("%w：祖先组 %d 不是空容器", ErrClientEntryRetirementBlocked, id)
				}
				doomed[id] = true
				changed = true
			}
		}
	}
	doomedPolicies := map[int64]bool{}
	for id, policy := range policies {
		if policy.Mode != "split" || len(policy.SplitGroups) == 0 {
			continue
		}
		all := true
		for _, g := range policy.SplitGroups {
			all = all && doomed[g.ID]
		}
		if all {
			doomedPolicies[id] = true
		}
	}
	if doomedPolicies[req.FallbackPolicyID] {
		return p, fmt.Errorf("%w：不能同时删除保底规则", ErrClientEntryRetirementInvalid)
	}
	for _, cm := range s.CollectionMembers {
		if cm.GroupID != nil && (doomed[*cm.GroupID] || replacements[*cm.GroupID]) || cm.PolicyID != nil && relevantPolicies[*cm.PolicyID] {
			p.Preview.Blockers = append(p.Preview.Blockers, "选中组、替代组或保底仍属于合集，需先单独核对合集范围")
		}
	}
	for _, id := range req.GroupIDs {
		g := groups[id]
		p.Preview.SelectedGroups = append(p.Preview.SelectedGroups, ClientEntryRetirementGroup{GroupID: id, PolicyID: g.PolicyID, Name: g.Name, Host: g.EntryHost, AssignedUsers: assignedCounts[id]})
	}
	for _, id := range retirementIDs(doomed) {
		if !selected[id] {
			p.Preview.RemovedAncestorIDs = append(p.Preview.RemovedAncestorIDs, id)
		}
	}
	p.GroupIDs = retirementIDs(doomed)
	p.PolicyIDs = retirementIDs(doomedPolicies)
	p.Preview.RemovedPolicyIDs = p.PolicyIDs
	// Membership is only counted as migrated when node scope, runtime UA and
	// priority also cover the old assignment. Earlier special rules are kept.
	replacementUsers := map[int64]map[int64]bool{}
	oldByUser := map[int64][]int64{}
	for _, a := range s.Assignments {
		if selected[a.GroupID] {
			oldByUser[a.UserID] = append(oldByUser[a.UserID], a.GroupID)
		}
		if doomed[a.GroupID] {
			p.Preview.RemovedAssignments++
		}
		if replacements[a.GroupID] {
			if replacementUsers[a.UserID] == nil {
				replacementUsers[a.UserID] = map[int64]bool{}
			}
			replacementUsers[a.UserID][a.GroupID] = true
		}
	}
	users := map[int64]retirementUser{}
	for _, u := range s.Users {
		users[u.ID] = u
	}
	fallback, hasFallback := policies[req.FallbackPolicyID]
	fallbackValid := hasFallback && fallback.Mode == ClientEntryUserPolicyModeStandard && fallback.Enabled == 1 && fallback.Action == cliententry.ActionOverride && fallback.EntryHost != ""
	for _, c := range fallback.Conditions {
		if c.Field == "ua" {
			fallbackValid = false
		}
	}
	if req.AllowFallback && !fallbackValid {
		p.Preview.Blockers = append(p.Preview.Blockers, "指定保底必须是启用的普通替换入口规则，且不能限制 UA")
	}
	for uid, oldIDs := range oldByUser {
		p.Preview.AssignedUsers++
		u, exists := users[uid]
		if !exists {
			p.Preview.DeletedUsers++
			continue
		}
		p.Preview.ExistingUsers++
		allCovered, canFallback := true, fallbackValid
		subject := cliententry.Subject{UserID: u.ID, Email: u.Email, PlanID: u.PlanID, RegistrationDays: clientEntrySimulationRegistrationDays(sql.NullInt64{Int64: u.CreatedAt, Valid: u.CreatedAt > 0}, now)}
		for _, oldID := range oldIDs {
			old := groups[oldID]
			op := policies[old.PolicyID]
			covered := false
			for newID := range replacementUsers[uid] {
				ng := groups[newID]
				np := policies[ng.PolicyID]
				if np.Enabled == 1 && ng.EntryHost != "" && retirementMembersCover(np.Members, op.Members) && retirementUAConditionsCover(np.Conditions, op.Conditions) && retirementPrecedes(ng, np, old, op) {
					covered = true
					break
				}
			}
			if !covered {
				allCovered = false
				canFallback = canFallback && retirementMembersCover(fallback.Members, op.Members)
				// A hide rule newly exposed between this old leaf and fallback would
				// remove nodes instead of delivering the fallback. UA overlap is checked
				// conservatively; a conditional hide cannot be assumed inapplicable.
				for _, candidate := range s.Policies {
					if candidate.Enabled != 1 || candidate.Action != cliententry.ActionHide || candidate.Mode != ClientEntryUserPolicyModeStandard {
						continue
					}
					afterOld := candidate.Sort > retirementGroupSort(old, op) || candidate.Sort == retirementGroupSort(old, op) && candidate.ID > op.ID
					beforeFallback := candidate.Sort < fallback.Sort || candidate.Sort == fallback.Sort && candidate.ID < fallback.ID
					if !afterOld || !beforeFallback {
						continue
					}
					nonUA := []cliententry.Condition{}
					for _, c := range candidate.Conditions {
						if c.Field != "ua" {
							nonUA = append(nonUA, c)
						}
					}
					overlap := false
					for _, m := range op.Members {
						if clientEntrySimulationHasMember(candidate.Members, m.ServerType, m.ServerID) {
							overlap = true
							break
						}
					}
					if overlap && cliententry.MatchAll(nonUA, subject) {
						canFallback = false
					}
				}
			}
		}
		if allCovered {
			p.Preview.ReplacementCoveredUsers++
			continue
		}
		if req.AllowFallback && canFallback && cliententry.MatchAll(fallback.Conditions, subject) {
			p.Preview.FallbackUsers++
		} else {
			p.Preview.UncoveredUsers++
		}
	}
	if p.Preview.UncoveredUsers > 0 {
		p.Preview.Blockers = append(p.Preview.Blockers, fmt.Sprintf("%d 名现存用户尚未被替代组完整覆盖；需明确允许回落，并保证保底覆盖节点与用户且中途无新增隐藏规则遮挡", p.Preview.UncoveredUsers))
	}
	monitors := map[int64]int64{}
	for _, m := range s.Monitors {
		monitors[m.ID] = m.PolicyID
	}
	targetSet := map[int64]bool{}
	for _, t := range s.Targets {
		pid := monitors[t.MonitorID]
		remove := doomedPolicies[pid]
		for gid := range selected {
			g := groups[gid]
			if g.PolicyID == pid && t.SourceKey == fmt.Sprintf("policy:%d:split-group:%d", pid, gid) {
				remove = true
				break
			}
		}
		if remove {
			targetSet[t.ID] = true
		}
	}
	p.TargetIDs = retirementIDs(targetSet)
	p.Preview.RemovedMonitorTargets = int64(len(p.TargetIDs))
	hosts := map[string]bool{}
	for _, g := range p.Preview.SelectedGroups {
		if g.Host != "" {
			hosts[g.Host] = true
		}
	}
	hostList := []string{}
	for host := range hosts {
		hostList = append(hostList, host)
	}
	sort.Strings(hostList)
	for _, host := range hostList {
		item := ClientEntryRetirementIP{Host: host, PoolIDs: []int64{}}
		policyReferences := int64(0)
		for _, policy := range s.Policies {
			if !doomedPolicies[policy.ID] && retirementSameHost(policy.EntryHost, host) {
				item.RemainingReferences++
				policyReferences++
			}
			for _, g := range policy.SplitGroups {
				if !doomed[g.ID] && retirementSameHost(g.EntryHost, host) {
					item.RemainingReferences++
					policyReferences++
				}
			}
		}
		for _, c := range s.Collections {
			if retirementSameHost(c.Host, host) {
				item.RemainingReferences++
			}
		}
		for _, g := range s.GroupIPs {
			if retirementSameHost(g.IP, host) {
				item.RemainingReferences++
			}
		}
		for _, n := range s.Nodes {
			if retirementSameHost(n.Host, host) {
				item.RemainingReferences++
			}
		}
		for _, t := range s.Targets {
			if retirementSameHost(t.Host, host) && !targetSet[t.ID] {
				item.RemainingReferences++
			}
		}
		for _, ip := range s.Pool {
			if retirementSameHost(ip.IP, host) {
				item.PoolIDs = append(item.PoolIDs, ip.ID)
			}
		}
		if len(item.PoolIDs) > 0 && item.RemainingReferences > 0 && policyReferences == 0 {
			p.Preview.Blockers = append(p.Preview.Blockers, fmt.Sprintf("入口 %s 还被节点、合集或其他配置引用，当前 IP 池无法表达该占用，不能自动回收", host))
		}
		item.Releasable = item.RemainingReferences == 0 && len(item.PoolIDs) > 0
		p.Preview.IPs = append(p.Preview.IPs, item)
	}
	p.Preview.CanExecute = len(p.Preview.Blockers) == 0
	return p, nil
}

func (s *DBService) PreviewClientEntryRetirement(ctx context.Context, actor int64, req ClientEntryRetirementPreviewRequest) (ClientEntryRetirementPreview, error) {
	req, err := normalizeRetirementRequest(req)
	if err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	if err = s.ensureClientEntryRetirement(ctx, actor); err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	tx, err := s.db.BeginTx(ctx, &sql.TxOptions{Isolation: sql.LevelRepeatableRead})
	if err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	defer tx.Rollback()
	snapshot, err := loadRetirementSnapshot(ctx, tx, req, false)
	if err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	now := time.Now().Unix()
	plan, err := buildRetirementPlan(req, snapshot, now)
	if err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	out := plan.Preview
	if err = retirementFallbackWarning(ctx, tx, req, &out, now); err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	out.ExpiresAt = now + int64(retirementLifetime/time.Second)
	out.PreviewHash = retirementDigest(struct {
		Request  ClientEntryRetirementPreviewRequest
		Snapshot retirementSnapshot
	}{req, snapshot})
	if _, err = tx.ExecContext(ctx, `DELETE FROM v2_client_entry_retirement WHERE actor_id=$1 AND expires_at < $2 AND receipt IS NULL`, actor, now-int64(24*time.Hour/time.Second)); err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	reqRaw, _ := json.Marshal(req)
	snapRaw, _ := json.Marshal(snapshot)
	previewRaw, _ := json.Marshal(out)
	err = tx.QueryRowContext(ctx, `INSERT INTO v2_client_entry_retirement(actor_id,request,snapshot,snapshot_hash,preview,created_at,expires_at) VALUES($1,$2,$3,$4,$5,$6,$7) RETURNING id`, actor, string(reqRaw), string(snapRaw), out.PreviewHash, string(previewRaw), now, out.ExpiresAt).Scan(&out.PreviewID)
	if err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	if err = tx.Commit(); err != nil {
		return ClientEntryRetirementPreview{}, err
	}
	return out, nil
}

func validateRetirementExecute(req ClientEntryRetirementExecuteRequest) error {
	h, err := hex.DecodeString(req.PreviewHash)
	if req.PreviewID <= 0 || err != nil || len(h) != 32 || hex.EncodeToString(h) != req.PreviewHash || len(req.IdempotencyKey) < 1 || len(req.IdempotencyKey) > 128 || strings.TrimSpace(req.IdempotencyKey) != req.IdempotencyKey || strings.ContainsAny(req.IdempotencyKey, "\x00\r\n") {
		return ErrClientEntryRetirementInvalid
	}
	return nil
}

func (s *DBService) ExecuteClientEntryRetirement(ctx context.Context, actor int64, req ClientEntryRetirementExecuteRequest) (ClientEntryRetirementReceipt, error) {
	var out ClientEntryRetirementReceipt
	ctx, cancel := context.WithTimeout(ctx, 90*time.Second)
	defer cancel()
	if err := validateRetirementExecute(req); err != nil {
		return out, err
	}
	if err := s.ensureClientEntryRetirement(ctx, actor); err != nil {
		return out, err
	}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return out, err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, `SET LOCAL lock_timeout='5s'`); err != nil {
		return out, err
	}
	if _, err = tx.ExecContext(ctx, `SET LOCAL statement_timeout='90s'`); err != nil {
		return out, err
	}
	// Lock the idempotency key before preview lookup; competing previews using
	// the same key cannot both mutate business tables.
	if _, err = tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock(hashtextextended($1,0))`, fmt.Sprintf("entry-retirement:%d:%s", actor, req.IdempotencyKey)); err != nil {
		return out, err
	}
	var previousID int64
	err = tx.QueryRowContext(ctx, `SELECT id FROM v2_client_entry_retirement WHERE actor_id=$1 AND idempotency_key=$2`, actor, req.IdempotencyKey).Scan(&previousID)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return out, err
	}
	if err == nil && previousID != req.PreviewID {
		return out, ErrClientEntryRetirementConflict
	}
	var requestRaw, snapshotRaw, previewRaw, receiptRaw []byte
	var snapshotHash string
	var expires int64
	var key sql.NullString
	err = tx.QueryRowContext(ctx, `SELECT request,snapshot,snapshot_hash,preview,expires_at,idempotency_key,receipt FROM v2_client_entry_retirement WHERE id=$1 AND actor_id=$2 FOR UPDATE`, req.PreviewID, actor).Scan(&requestRaw, &snapshotRaw, &snapshotHash, &previewRaw, &expires, &key, &receiptRaw)
	if errors.Is(err, sql.ErrNoRows) {
		return out, ErrClientEntryRetirementNotFound
	}
	if err != nil {
		return out, err
	}
	if snapshotHash != req.PreviewHash {
		return out, ErrClientEntryRetirementConflict
	}
	if len(receiptRaw) > 0 {
		if !key.Valid || key.String != req.IdempotencyKey {
			return out, ErrClientEntryRetirementConflict
		}
		if err = json.Unmarshal(receiptRaw, &out); err != nil {
			return out, err
		}
		out.Replayed = true
		return out, nil
	}
	if expires < time.Now().Unix() {
		return out, ErrClientEntryRetirementConflict
	}
	var request ClientEntryRetirementPreviewRequest
	var frozen retirementSnapshot
	var preview ClientEntryRetirementPreview
	if json.Unmarshal(requestRaw, &request) != nil || json.Unmarshal(snapshotRaw, &frozen) != nil || json.Unmarshal(previewRaw, &preview) != nil {
		return out, errors.New("invalid stored retirement preview")
	}
	if !preview.CanExecute {
		return out, fmt.Errorf("%w：%s", ErrClientEntryRetirementBlocked, strings.Join(preview.Blockers, "；"))
	}
	var revision int64
	if err = tx.QueryRowContext(ctx, `SELECT revision FROM v2_client_entry_monitor_config WHERE id=1 FOR UPDATE`).Scan(&revision); err != nil {
		return out, err
	}
	if _, err = lockClientEntryMonitorTopology(ctx, tx); err != nil {
		if errors.Is(err, ErrClientEntryMonitorRevisionConflict) {
			return out, ErrClientEntryRetirementConflict
		}
		return out, err
	}
	if _, err = tx.ExecContext(ctx, `LOCK TABLE v2_client_entry_user_policy,v2_client_entry_user_policy_split_group,v2_client_entry_user_policy_member,v2_client_entry_user_policy_split_assignment,v2_client_entry_collection,v2_client_entry_collection_member,v2_client_entry_group_ip IN SHARE ROW EXCLUSIVE MODE`); err != nil {
		return out, err
	}
	// Host edits must not race the last reference check. Health samples remain
	// writable; only configuration and pool inventory receive table locks.
	if _, err = tx.ExecContext(ctx, `LOCK TABLE v2_client_entry_monitor_target,v2_client_entry_backup_ip IN SHARE ROW EXCLUSIVE MODE`); err != nil {
		return out, err
	}
	tables := []string{}
	for _, table := range managedServerTypeTable {
		tables = append(tables, table)
	}
	sort.Strings(tables)
	for _, table := range tables {
		var exists bool
		if err = tx.QueryRowContext(ctx, `SELECT to_regclass($1) IS NOT NULL`, table).Scan(&exists); err != nil {
			return out, err
		}
		if exists {
			if _, err = tx.ExecContext(ctx, `LOCK TABLE `+quoteIdentifier(table)+` IN SHARE MODE`); err != nil {
				return out, err
			}
		}
	}
	snapshot, err := loadRetirementSnapshot(ctx, tx, request, true)
	if err != nil {
		return out, err
	}
	if retirementDigest(struct {
		Request  ClientEntryRetirementPreviewRequest
		Snapshot retirementSnapshot
	}{request, snapshot}) != snapshotHash {
		return out, ErrClientEntryRetirementConflict
	}
	now := time.Now().Unix()
	plan, err := buildRetirementPlan(request, snapshot, now)
	if err != nil {
		return out, err
	}
	if !plan.Preview.CanExecute {
		return out, fmt.Errorf("%w：%s", ErrClientEntryRetirementBlocked, strings.Join(plan.Preview.Blockers, "；"))
	}
	// Preserve removed health/auto-task state for an operator to reconstruct;
	// its changing fields intentionally were not used in preview CAS.
	var audit json.RawMessage
	err = tx.QueryRowContext(ctx, `SELECT jsonb_build_object(
 'monitor_states',COALESCE((SELECT jsonb_agg(s ORDER BY id) FROM v2_client_entry_monitor_state s WHERE target_id=ANY($1::bigint[])),'[]'::jsonb),
 'auto_operations',COALESCE((SELECT jsonb_agg(o ORDER BY id) FROM v2_client_entry_auto_split_operation o WHERE target_id=ANY($1::bigint[]) OR policy_id=ANY($2::bigint[])),'[]'::jsonb))`, plan.TargetIDs, plan.PolicyIDs).Scan(&audit)
	if err != nil {
		return out, err
	}
	if _, err = tx.ExecContext(ctx, `UPDATE v2_client_entry_retirement SET snapshot=snapshot || jsonb_build_object('execution_audit',$2::jsonb) WHERE id=$1`, req.PreviewID, string(audit)); err != nil {
		return out, err
	}
	result, err := tx.ExecContext(ctx, `UPDATE v2_client_entry_auto_split_operation SET status='cancelled',last_error=$3,completed_at=$4,updated_at=$4 WHERE status='pending' AND (target_id=ANY($1::bigint[]) OR policy_id=ANY($2::bigint[]))`, plan.TargetIDs, plan.PolicyIDs, fmt.Sprintf("entry-retirement preview %d: %s", req.PreviewID, request.Reason), now)
	if err != nil {
		return out, err
	}
	cancelled, err := result.RowsAffected()
	if err != nil {
		return out, err
	}
	// Explicit removal order also works on installations whose legacy group
	// and member relations predate foreign keys.
	for _, statement := range []struct {
		SQL string
		IDs []int64
	}{
		{`DELETE FROM v2_client_entry_monitor_target WHERE id=ANY($1::bigint[])`, plan.TargetIDs},
		{`DELETE FROM v2_client_entry_user_policy_split_assignment WHERE group_id=ANY($1::bigint[])`, plan.GroupIDs},
		{`DELETE FROM v2_client_entry_user_policy_split_group WHERE id=ANY($1::bigint[])`, plan.GroupIDs},
		{`DELETE FROM v2_client_entry_user_policy_member WHERE policy_id=ANY($1::bigint[])`, plan.PolicyIDs},
		{`DELETE FROM v2_client_entry_monitor WHERE policy_id=ANY($1::bigint[])`, plan.PolicyIDs},
		{`DELETE FROM v2_client_entry_user_policy WHERE id=ANY($1::bigint[])`, plan.PolicyIDs},
	} {
		if _, err = tx.ExecContext(ctx, statement.SQL, statement.IDs); err != nil {
			return out, err
		}
	}
	if err = tx.QueryRowContext(ctx, `UPDATE v2_client_entry_monitor_config SET revision=revision+1,updated_at=$1 WHERE id=1 RETURNING revision`, now).Scan(&revision); err != nil {
		return out, err
	}
	out = ClientEntryRetirementReceipt{PreviewID: req.PreviewID, OperationID: req.PreviewID, Status: "completed", Committed: true, AppliedAt: now, RemovedGroups: int64(len(request.GroupIDs)), RemovedAncestors: int64(len(plan.Preview.RemovedAncestorIDs)), RemovedPolicyIDs: plan.PolicyIDs, RemovedAssignments: plan.Preview.RemovedAssignments, RemovedMonitorTargets: int64(len(plan.TargetIDs)), CancelledPendingOperations: cancelled, ReleasedIPs: []string{}, RetainedIPs: []string{}, MonitorRevision: revision, PreservedOtherConfiguration: true}
	for _, ip := range plan.Preview.IPs {
		if ip.Releasable {
			out.ReleasedIPs = append(out.ReleasedIPs, ip.Host)
		} else {
			out.RetainedIPs = append(out.RetainedIPs, ip.Host)
		}
	}
	receiptRaw, err = json.Marshal(out)
	if err != nil {
		return ClientEntryRetirementReceipt{}, err
	}
	if _, err = tx.ExecContext(ctx, `UPDATE v2_client_entry_retirement SET idempotency_key=$2,applied_at=$3,receipt=$4 WHERE id=$1`, req.PreviewID, req.IdempotencyKey, now, string(receiptRaw)); err != nil {
		return ClientEntryRetirementReceipt{}, err
	}
	if err = tx.Commit(); err != nil {
		return ClientEntryRetirementReceipt{}, err
	}
	s.markClientEntryMonitorTargetsDirty()
	return out, nil
}

// Receipt reads must remain genuinely read-only during unknown-outcome recovery.
func (s *DBService) GetClientEntryRetirement(ctx context.Context, actor, id int64) (ClientEntryRetirementReceipt, error) {
	var out ClientEntryRetirementReceipt
	if s == nil || s.db == nil {
		return out, ErrUnavailable
	}
	if id <= 0 {
		return out, ErrClientEntryRetirementInvalid
	}
	if err := authorizeEntryEvidence(ctx, s.db, actor, true); err != nil {
		return out, err
	}
	var exists bool
	if err := s.db.QueryRowContext(ctx, `SELECT to_regclass('v2_client_entry_retirement') IS NOT NULL`).Scan(&exists); err != nil {
		return out, err
	}
	if !exists {
		return out, ErrClientEntryRetirementNotFound
	}
	var raw []byte
	var expires int64
	var executable bool
	err := s.db.QueryRowContext(ctx, `SELECT receipt,expires_at,COALESCE((preview->>'can_execute')::boolean,false) FROM v2_client_entry_retirement WHERE id=$1 AND actor_id=$2`, id, actor).Scan(&raw, &expires, &executable)
	if errors.Is(err, sql.ErrNoRows) {
		return out, ErrClientEntryRetirementNotFound
	}
	if err != nil {
		return out, err
	}
	if len(raw) > 0 {
		if err = json.Unmarshal(raw, &out); err != nil {
			return out, err
		}
		return out, nil
	}
	out.PreviewID = id
	out.Status = "previewed"
	if !executable {
		out.Status = "blocked"
	}
	if expires < time.Now().Unix() {
		out.Status = "expired"
	}
	return out, nil
}

func retirementFallbackWarning(ctx context.Context, tx *sql.Tx, req ClientEntryRetirementPreviewRequest, out *ClientEntryRetirementPreview, now int64) error {
	if !req.AllowFallback || out.FallbackUsers == 0 {
		return nil
	}
	var targets, fresh, failed int64
	err := tx.QueryRowContext(ctx, `SELECT count(DISTINCT t.id),
 count(DISTINCT t.id) FILTER (WHERE m.enabled=1 AND p.enabled=1 AND p.last_heartbeat_at >= $2-GREATEST(m.check_interval_sec*3,90) AND s.last_reported_at >= $2-GREATEST(m.check_interval_sec*3,90) AND s.last_success=1 AND s.consecutive_success>=m.success_threshold),
 count(DISTINCT t.id) FILTER (WHERE m.enabled=1 AND p.enabled=1 AND s.last_reported_at >= $2-GREATEST(m.check_interval_sec*3,90) AND s.last_success=0 AND s.consecutive_failure>=m.failure_threshold)
 FROM v2_client_entry_monitor m JOIN v2_client_entry_monitor_target t ON t.monitor_id=m.id
 LEFT JOIN v2_client_entry_monitor_state s ON s.target_id=t.id LEFT JOIN v2_dns_probe p ON p.id=s.probe_id WHERE m.policy_id=$1`, req.FallbackPolicyID, now).Scan(&targets, &fresh, &failed)
	if err != nil {
		return err
	}
	switch {
	case targets == 0:
		out.Warnings = append(out.Warnings, "保底尚未配置监测；本预览仅核对规则覆盖，未证明入口健康")
	case failed > 0:
		out.Warnings = append(out.Warnings, "保底监测存在近期确认失败，请先核对健康状态；本预览未主动探测")
	case fresh < targets:
		out.Warnings = append(out.Warnings, "保底部分目标缺少近期成功监测，当前健康状态尚不能确认")
	default:
		out.Warnings = append(out.Warnings, "保底目标已有近期成功探测记录；这不代表用户客户端已更新或连接成功")
	}
	return nil
}
