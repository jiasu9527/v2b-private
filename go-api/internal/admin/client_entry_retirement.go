const retirementLifetime = 15 * time.Minute

var retirementSchemaStates sync.Map

func (s *DBService) ensureClientEntryRetirement(ctx context.Context, actor int64) error {
	if s == nil || s.db == nil {
		return ErrUnavailable
	}
	if err := authorizeEntryEvidence(ctx, s.db, actor, true); err != nil {
		return err
	}
	state, _ := retirementSchemaStates.LoadOrStore(s.db, &evidenceSchemaState{})
	v := state.(*evidenceSchemaState)
	v.once.Do(func() {
		if v.err = s.ensureClientEntrySchema(ctx); v.err != nil {
			return
		}
		if v.err = s.ensureDNSFailoverSchema(ctx); v.err != nil {
			return
		}
		if v.err = platformpostgres.EnsureClientEntryMonitorSchema(ctx, s.db); v.err != nil {
			return
		}
		_, v.err = s.db.ExecContext(ctx, `CREATE TABLE IF NOT EXISTS v2_client_entry_retirement (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL, request JSONB NOT NULL, snapshot JSONB NOT NULL,
 snapshot_hash TEXT NOT NULL, preview JSONB NOT NULL,
 created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
 idempotency_key TEXT, applied_at BIGINT, receipt JSONB,
 UNIQUE(actor_id,idempotency_key)
)`)
	})
	if v.err != nil {
		retirementSchemaStates.Delete(s.db)
	}
	return v.err
}

func normalizeRetirementRequest(req ClientEntryRetirementPreviewRequest) (ClientEntryRetirementPreviewRequest, error) {
	req.Reason = strings.TrimSpace(req.Reason)
	if len(req.GroupIDs) < 1 || len(req.GroupIDs) > 100 || len(req.ReplacementGroupIDs) > 100 || req.FallbackPolicyID < 0 || req.AllowFallback && req.FallbackPolicyID < 1 || !req.AllowFallback && req.FallbackPolicyID != 0 || !utf8.ValidString(req.Reason) || len([]rune(req.Reason)) < 1 || len([]rune(req.Reason)) > 500 {
		return req, ErrClientEntryRetirementInvalid
	}
	seen := map[int64]bool{}
	for _, ids := range [][]int64{req.GroupIDs, req.ReplacementGroupIDs} {
		for _, id := range ids {
			if id < 1 || seen[id] {
				return req, ErrClientEntryRetirementInvalid
			}
			seen[id] = true
		}
	}
	req.GroupIDs = append([]int64(nil), req.GroupIDs...)
	req.ReplacementGroupIDs = append([]int64(nil), req.ReplacementGroupIDs...)
	sort.Slice(req.GroupIDs, func(i, j int) bool { return req.GroupIDs[i] < req.GroupIDs[j] })
	sort.Slice(req.ReplacementGroupIDs, func(i, j int) bool { return req.ReplacementGroupIDs[i] < req.ReplacementGroupIDs[j] })
	return req, nil
}

