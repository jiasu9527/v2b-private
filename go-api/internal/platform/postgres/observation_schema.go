package postgres

import (
	"context"
	"database/sql"
	"fmt"
)

// EnsureObservationSchema is additive and intentionally separate from the
// legacy sensitive-domain audit.
func EnsureObservationSchema(ctx context.Context, db *sql.DB) error {
	if db == nil {
		return fmt.Errorf("db is nil")
	}
	statements := []string{
		`CREATE TABLE IF NOT EXISTS v2_node_observation_config (
			node_type varchar(16) NOT NULL,
			node_id bigint NOT NULL,
			enabled boolean NOT NULL DEFAULT false,
			mode varchar(16) NOT NULL DEFAULT 'allowlist',
			token_hash bytea NOT NULL,
			allowed_user_ids jsonb NOT NULL DEFAULT '[]',
			created_at bigint NOT NULL,
			updated_at bigint NOT NULL,
			PRIMARY KEY (node_type,node_id)
		)`,
		`ALTER TABLE v2_node_observation_config ADD COLUMN IF NOT EXISTS mode varchar(16) NOT NULL DEFAULT 'allowlist'`,
		`CREATE TABLE IF NOT EXISTS v2_node_observation_capability (
			node_type varchar(16) NOT NULL,
			node_id bigint NOT NULL,
			capability varchar(16) NOT NULL,
			last_seen_at bigint NOT NULL,
			PRIMARY KEY (node_type,node_id)
		)`,
		`CREATE TABLE IF NOT EXISTS v2_node_observation_event (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			node_type varchar(16) NOT NULL,
			node_id bigint NOT NULL,
			event_id varchar(64) NOT NULL,
			user_id bigint NOT NULL,
			occurred_at bigint NOT NULL,
			client_ip varchar(45) NOT NULL DEFAULT '',
			target_host varchar(253) NOT NULL DEFAULT '',
			target_ip varchar(45) NOT NULL DEFAULT '',
			target_port integer NOT NULL,
			network varchar(8) NOT NULL,
			result varchar(16) NOT NULL,
			uplink_bytes bigint NOT NULL DEFAULT 0,
			downlink_bytes bigint NOT NULL DEFAULT 0,
			received_at bigint NOT NULL,
			UNIQUE (node_type,node_id,event_id)
		)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_observation_event_time ON v2_node_observation_event(occurred_at DESC,id DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_observation_event_user_time ON v2_node_observation_event(user_id,occurred_at DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_observation_event_node_time ON v2_node_observation_event(node_type,node_id,occurred_at DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_observation_event_host_time ON v2_node_observation_event(target_host,occurred_at DESC) WHERE target_host<>''`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_observation_event_ip_time ON v2_node_observation_event(target_ip,occurred_at DESC) WHERE target_ip<>''`,
	}
	for _, statement := range statements {
		if _, err := db.ExecContext(ctx, statement); err != nil {
			return fmt.Errorf("ensure observation schema: %w", err)
		}
	}
	return nil
}
