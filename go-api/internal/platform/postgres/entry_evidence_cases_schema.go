package postgres

import (
	"context"
	"database/sql"
	"fmt"
)

// EnsureEntryEvidenceCasesSchema follows EnsureClientEntrySchema. Frozen evidence
// intentionally has no foreign keys to mutable users/rules or short-lived logs.
func EnsureEntryEvidenceCasesSchema(ctx context.Context, db *sql.DB) error {
	if db == nil {
		return fmt.Errorf("db is nil")
	}
	for _, stmt := range entryEvidenceCasesStatements {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("ensure entry evidence cases: %w", err)
		}
	}
	return EnsureEntryEvidenceObservationSchema(ctx, db)
}

var entryEvidenceCasesStatements = []string{
	`CREATE TABLE IF NOT EXISTS v2_entry_evidence_case (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_by BIGINT NOT NULL, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
 parent_case_id BIGINT NOT NULL DEFAULT 0,
 status TEXT NOT NULL DEFAULT 'frozen' CHECK(status IN ('frozen','executed')),
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>0),
 snapshot JSONB NOT NULL, topology_revision TEXT NOT NULL,
 observation TEXT NOT NULL DEFAULT '', conclusion TEXT NOT NULL DEFAULT '', execution JSONB DEFAULT NULL
 )`,
	`CREATE TABLE IF NOT EXISTS v2_entry_evidence_case_candidate (
 case_id BIGINT NOT NULL REFERENCES v2_entry_evidence_case(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL, selected BOOLEAN NOT NULL, branch TEXT NOT NULL DEFAULT '',
 evidence JSONB NOT NULL, PRIMARY KEY(case_id,user_id)
 )`,
	`CREATE INDEX IF NOT EXISTS idx_entry_evidence_case_parent ON v2_entry_evidence_case(parent_case_id,id)`,
	`CREATE INDEX IF NOT EXISTS idx_entry_evidence_case_candidate_selected ON v2_entry_evidence_case_candidate(case_id,selected,user_id)`,
}
