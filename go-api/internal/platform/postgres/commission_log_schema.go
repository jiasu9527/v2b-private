package postgres

import (
	"context"
	"database/sql"
	"fmt"
)

// Commission log visibility is separate from settlement state. Financial
// evidence and original amounts stay intact when a record is hidden/restored.
func EnsureCommissionLogSchema(ctx context.Context, db *sql.DB) error {
	if db == nil {
		return fmt.Errorf("db is nil")
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock(782146291065)`); err != nil {
		return err
	}
	for _, stmt := range []string{
		`ALTER TABLE v2_commission_log ADD COLUMN IF NOT EXISTS deleted_at BIGINT DEFAULT NULL`,
		`ALTER TABLE v2_commission_log ADD COLUMN IF NOT EXISTS deleted_by BIGINT DEFAULT NULL`,
		`ALTER TABLE v2_commission_log ADD COLUMN IF NOT EXISTS delete_reason TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE v2_commission_log ADD COLUMN IF NOT EXISTS visibility_version BIGINT NOT NULL DEFAULT 0`,
		`CREATE INDEX IF NOT EXISTS idx_v2_commission_log_visibility_inviter_time ON v2_commission_log(invite_user_id,deleted_at,created_at,id)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_commission_log_trade ON v2_commission_log(trade_no)`,
		`CREATE TABLE IF NOT EXISTS v2_commission_log_preview (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 token_hash CHAR(64) NOT NULL UNIQUE,
 actor_id BIGINT NOT NULL,
 action VARCHAR(16) NOT NULL CHECK (action IN ('delete','restore')),
 filters JSONB NOT NULL,
 snapshot JSONB NOT NULL,
 snapshot_hash CHAR(64) NOT NULL,
 reason TEXT NOT NULL,
 all_records BOOLEAN NOT NULL,
 record_count BIGINT NOT NULL,
 total_amount BIGINT NOT NULL,
 created_at BIGINT NOT NULL,
 expires_at BIGINT NOT NULL,
 applied_operation_id BIGINT DEFAULT NULL
)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_commission_log_preview_expiry ON v2_commission_log_preview(expires_at) WHERE applied_operation_id IS NULL`,
		`CREATE TABLE IF NOT EXISTS v2_commission_log_operation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL,
 idempotency_key VARCHAR(128) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 preview_id BIGINT NOT NULL UNIQUE,
 action VARCHAR(16) NOT NULL CHECK (action IN ('delete','restore')),
 reason TEXT NOT NULL,
 record_count BIGINT NOT NULL,
 total_amount BIGINT NOT NULL,
 snapshot JSONB NOT NULL,
 applied_at BIGINT NOT NULL,
 receipt JSONB NOT NULL DEFAULT '{}',
 UNIQUE(actor_id,idempotency_key)
)`,
	} {
		if _, err = tx.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("ensure commission log visibility schema: %w", err)
		}
	}
	return tx.Commit()
}
