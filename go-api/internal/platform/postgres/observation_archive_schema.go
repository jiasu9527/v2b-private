package postgres

import (
	"context"
	"database/sql"
	"fmt"
)

// Compressed blocks live in the same database as hot events. A transaction can
// publish a verified archive and remove its original rows atomically, so queries
// cannot observe a file rename/database deletion half-migration.
func EnsureObservationArchiveSchema(ctx context.Context, db *sql.DB) error {
	if db == nil {
		return fmt.Errorf("db is nil")
	}
	statements := []string{
		`CREATE TABLE IF NOT EXISTS v2_node_observation_archive (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			hour_at bigint NOT NULL CHECK (hour_at>=0 AND hour_at%3600=0),
			user_id bigint NOT NULL CHECK (user_id>0),
			first_at bigint NOT NULL,
			last_at bigint NOT NULL,
			event_count bigint NOT NULL CHECK (event_count BETWEEN 1 AND 10000),
			known_events bigint NOT NULL CHECK (known_events BETWEEN 0 AND event_count),
			payload bytea NOT NULL CHECK (octet_length(payload) BETWEEN 1 AND 33554432),
			payload_sha256 bytea NOT NULL CHECK (octet_length(payload_sha256)=32),
			event_bloom bytea NOT NULL CHECK (octet_length(event_bloom) BETWEEN 64 AND 40000),
			node_ids bigint[] NOT NULL,
			target_hosts text[] NOT NULL,
			target_ips text[] NOT NULL,
			CHECK (first_at>=hour_at AND last_at>=first_at AND last_at<hour_at+3600)
		)`,
		// The payload is already gzip-compressed and checksum-verified. Avoid
		// wasting CPU trying PostgreSQL's row compression a second time.
		`ALTER TABLE v2_node_observation_archive ALTER COLUMN payload SET STORAGE EXTERNAL`,
		`CREATE INDEX IF NOT EXISTS idx_observation_archive_user_time ON v2_node_observation_archive(user_id,last_at DESC,id DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_observation_archive_time ON v2_node_observation_archive(hour_at DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_observation_archive_last_time ON v2_node_observation_archive(last_at DESC,id DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_observation_archive_nodes ON v2_node_observation_archive USING GIN(node_ids)`,
		`CREATE INDEX IF NOT EXISTS idx_observation_archive_hosts ON v2_node_observation_archive USING GIN(target_hosts)`,
		`CREATE INDEX IF NOT EXISTS idx_observation_archive_ips ON v2_node_observation_archive USING GIN(target_ips)`,
	}
	for _, statement := range statements {
		if _, err := db.ExecContext(ctx, statement); err != nil {
			return fmt.Errorf("ensure observation archive schema: %w", err)
		}
	}
	return nil
}
